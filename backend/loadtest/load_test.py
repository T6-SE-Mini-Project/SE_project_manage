"""Concurrent-load test for OBS-NF-005 / TC-OBS-023 (issue #17).

Drives a running Online Book Store deployment with a configurable number
of concurrent customer sessions and reports the response-time
distribution, so the scalability requirement ("the system supports 500
concurrent users while maintaining the required response time") can be
measured instead of assumed.

Design notes
------------

- Each simulated user gets its own cookie jar, so each one is a distinct
  Django session with its own cart. 500 users therefore means 500
  concurrent sessions, not 500 requests on one session.
- Users run in a thread pool sized to the user count, and all of them
  wait on one barrier before starting, so the load is genuinely
  concurrent rather than staggered.
- Only read-mostly catalogue traffic is generated by default. Write
  traffic (``--include-cart``) adds a book to each user's cart, which
  mutates data, so it is opt-in and should be pointed at a throwaway
  database.
- The exit status is non-zero when the measured percentile misses the
  threshold, so the harness can also run as a gate in CI.

Usage
-----

::

    # Start the application under a production-style server first, e.g.
    #   gunicorn config.wsgi:application --workers 4 --threads 8 \
    #       --bind 127.0.0.1:8001
    python loadtest/load_test.py --users 500 --requests-per-user 4 \
        --base-url http://127.0.0.1:8001 \
        --max-response-time 3.0 --percentile 95 \
        --json-out ../Docs/evidence/tc-obs-023.json

This file deliberately uses only the standard library so the harness can
run anywhere the application runs, without extra dependencies.
"""

from __future__ import annotations

import argparse
import json
import platform
import statistics
import sys
import threading
import time
import urllib.error
import urllib.parse
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from dataclasses import asdict, dataclass, field
from http.cookiejar import CookieJar

#: Catalogue requests one simulated user cycles through. Each entry is a
#: (label, path) pair; paths are appended to the base URL.
SCENARIO_REQUESTS = [
    ("catalogue", "/api/books/"),
    ("search", "/api/books/?q=code"),
    ("filter", "/api/books/?available=true&max_price=60"),
    ("categories", "/api/books/categories/"),
]


@dataclass
class Sample:
    """One measured request."""

    label: str
    seconds: float
    status: int
    ok: bool
    error: str = ""


@dataclass
class Report:
    """Aggregated result of a load-test run."""

    users: int
    requests_per_user: int
    total_requests: int
    failed_requests: int
    wall_seconds: float
    throughput_rps: float
    threshold_seconds: float
    percentile: int
    percentile_seconds: float
    mean_seconds: float
    median_seconds: float
    min_seconds: float
    max_seconds: float
    within_threshold: int
    within_threshold_ratio: float
    passed: bool
    by_label: dict = field(default_factory=dict)
    errors: dict = field(default_factory=dict)
    environment: dict = field(default_factory=dict)
    base_url: str = ""
    started_at: str = ""


def _percentile(values, percentile):
    """Nearest-rank percentile of ``values`` (already a non-empty list)."""
    ordered = sorted(values)
    if len(ordered) == 1:
        return ordered[0]
    rank = max(1, int(round(percentile / 100 * len(ordered))))
    return ordered[min(rank, len(ordered)) - 1]


class SimulatedUser:
    """One customer session with its own cookies."""

    def __init__(self, base_url, timeout):
        self.base_url = base_url.rstrip("/")
        self.timeout = timeout
        self.cookies = CookieJar()
        self.opener = urllib.request.build_opener(
            urllib.request.HTTPCookieProcessor(self.cookies)
        )

    def get(self, label, path):
        request = urllib.request.Request(
            f"{self.base_url}{path}",
            headers={"Accept": "application/json"},
        )
        started = time.perf_counter()

        try:
            with self.opener.open(request, timeout=self.timeout) as response:
                response.read()
                status = response.status
            elapsed = time.perf_counter() - started
            return Sample(label, elapsed, status, 200 <= status < 400)
        except urllib.error.HTTPError as exc:
            exc.read()
            return Sample(
                label,
                time.perf_counter() - started,
                exc.code,
                False,
                f"HTTP {exc.code}",
            )
        except Exception as exc:  # noqa: BLE001 - recorded as a failure
            return Sample(
                label,
                time.perf_counter() - started,
                0,
                False,
                f"{type(exc).__name__}: {exc}",
            )

    def post_json(self, label, path, payload):
        """POST JSON with the CSRF token Django requires for writes."""
        csrf = self.get("csrf", "/api/csrf/")
        if not csrf.ok:
            return csrf

        token = ""
        for cookie in self.cookies:
            if cookie.name == "csrftoken":
                token = cookie.value or ""

        body = json.dumps(payload).encode("utf-8")
        request = urllib.request.Request(
            f"{self.base_url}{path}",
            data=body,
            method="POST",
            headers={
                "Accept": "application/json",
                "Content-Type": "application/json",
                "X-CSRFToken": token,
                "Referer": self.base_url,
            },
        )
        started = time.perf_counter()

        try:
            with self.opener.open(request, timeout=self.timeout) as response:
                response.read()
                status = response.status
            return Sample(
                label, time.perf_counter() - started, status, 200 <= status < 400
            )
        except urllib.error.HTTPError as exc:
            exc.read()
            return Sample(
                label,
                time.perf_counter() - started,
                exc.code,
                False,
                f"HTTP {exc.code}",
            )
        except Exception as exc:  # noqa: BLE001 - recorded as a failure
            return Sample(
                label,
                time.perf_counter() - started,
                0,
                False,
                f"{type(exc).__name__}: {exc}",
            )


def _run_user(base_url, timeout, repeats, barrier, include_cart, book_id):
    """Run one simulated user's requests and return its samples."""
    user = SimulatedUser(base_url, timeout)
    samples = []

    # Hold every user here so the measured window is concurrent.
    barrier.wait()

    for _ in range(repeats):
        for label, path in SCENARIO_REQUESTS:
            samples.append(user.get(label, path))

        if include_cart:
            samples.append(
                user.post_json(
                    "add_to_cart",
                    "/api/cart/items/",
                    {"book_id": book_id, "quantity": 1},
                )
            )

    return samples


def run_load_test(
    base_url,
    users,
    requests_per_user,
    timeout,
    threshold,
    percentile,
    include_cart=False,
    book_id=1,
):
    """Run the load test and return a :class:`Report`."""
    barrier = threading.Barrier(users)
    started_at = time.strftime("%Y-%m-%dT%H:%M:%S%z")
    wall_started = time.perf_counter()

    with ThreadPoolExecutor(max_workers=users) as pool:
        futures = [
            pool.submit(
                _run_user,
                base_url,
                timeout,
                requests_per_user,
                barrier,
                include_cart,
                book_id,
            )
            for _ in range(users)
        ]
        samples = [
            sample for future in futures for sample in future.result()
        ]

    wall_seconds = time.perf_counter() - wall_started

    durations = [sample.seconds for sample in samples]
    successful = [sample for sample in samples if sample.ok]
    failed = [sample for sample in samples if not sample.ok]
    within = [value for value in durations if value <= threshold]

    by_label = {}
    for sample in samples:
        bucket = by_label.setdefault(
            sample.label,
            {"requests": 0, "failed": 0, "seconds": []},
        )
        bucket["requests"] += 1
        bucket["failed"] += 0 if sample.ok else 1
        bucket["seconds"].append(sample.seconds)

    for label, bucket in by_label.items():
        values = bucket.pop("seconds")
        bucket["mean_seconds"] = round(statistics.fmean(values), 4)
        bucket["max_seconds"] = round(max(values), 4)
        bucket[f"p{percentile}_seconds"] = round(
            _percentile(values, percentile), 4
        )

    errors = {}
    for sample in failed:
        errors[sample.error] = errors.get(sample.error, 0) + 1

    measured_percentile = _percentile(durations, percentile)

    return Report(
        users=users,
        requests_per_user=requests_per_user,
        total_requests=len(samples),
        failed_requests=len(failed),
        wall_seconds=round(wall_seconds, 3),
        throughput_rps=round(len(samples) / wall_seconds, 2)
        if wall_seconds
        else 0.0,
        threshold_seconds=threshold,
        percentile=percentile,
        percentile_seconds=round(measured_percentile, 4),
        mean_seconds=round(statistics.fmean(durations), 4),
        median_seconds=round(statistics.median(durations), 4),
        min_seconds=round(min(durations), 4),
        max_seconds=round(max(durations), 4),
        within_threshold=len(within),
        within_threshold_ratio=round(len(within) / len(durations), 4),
        # The run passes only when every request succeeded and the
        # measured percentile is within the required response time.
        passed=bool(
            not failed
            and measured_percentile <= threshold
            and len(successful) == len(samples)
        ),
        by_label=by_label,
        errors=errors,
        environment={
            "python": platform.python_version(),
            "platform": platform.platform(),
        },
        base_url=base_url,
        started_at=started_at,
    )


def format_report(report):
    """Render a human-readable summary for the evidence log."""
    lines = [
        "TC-OBS-023 / OBS-NF-005 concurrent load test",
        "=" * 44,
        f"Target                : {report.base_url}",
        f"Started               : {report.started_at}",
        f"Concurrent users      : {report.users}",
        f"Requests per user     : "
        f"{report.requests_per_user} cycles "
        f"({report.total_requests} requests total)",
        f"Wall clock            : {report.wall_seconds}s "
        f"({report.throughput_rps} requests/second)",
        f"Failed requests       : {report.failed_requests}",
        "",
        f"Response time (seconds), threshold {report.threshold_seconds}s:",
        f"  min                 : {report.min_seconds}",
        f"  median              : {report.median_seconds}",
        f"  mean                : {report.mean_seconds}",
        f"  p{report.percentile:<18}: {report.percentile_seconds}",
        f"  max                 : {report.max_seconds}",
        f"  within threshold    : {report.within_threshold}"
        f"/{report.total_requests} "
        f"({report.within_threshold_ratio * 100:.2f}%)",
        "",
        "Per request type:",
    ]

    for label, bucket in sorted(report.by_label.items()):
        lines.append(
            f"  {label:<12} n={bucket['requests']:<6} "
            f"failed={bucket['failed']:<4} "
            f"mean={bucket['mean_seconds']:<8} "
            f"p{report.percentile}={bucket[f'p{report.percentile}_seconds']:<8} "
            f"max={bucket['max_seconds']}"
        )

    if report.errors:
        lines.extend(["", "Errors:"])
        for error, count in sorted(
            report.errors.items(), key=lambda item: -item[1]
        ):
            lines.append(f"  {count:>6} x {error}")

    lines.extend(
        [
            "",
            f"RESULT: {'PASS' if report.passed else 'FAIL'}",
        ]
    )

    return "\n".join(lines)


def build_parser():
    parser = argparse.ArgumentParser(
        description=(
            "Concurrent load test for the Online Book Store "
            "(OBS-NF-005, TC-OBS-023)."
        )
    )
    parser.add_argument(
        "--base-url",
        default="http://127.0.0.1:8000",
        help="Base URL of the running application.",
    )
    parser.add_argument(
        "--users",
        type=int,
        default=500,
        help="Number of concurrent user sessions (default: 500).",
    )
    parser.add_argument(
        "--requests-per-user",
        type=int,
        default=2,
        help="How many times each user repeats the request cycle.",
    )
    parser.add_argument(
        "--timeout",
        type=float,
        default=30.0,
        help="Per-request timeout in seconds.",
    )
    parser.add_argument(
        "--max-response-time",
        type=float,
        default=3.0,
        dest="threshold",
        help="Required response time in seconds (default: 3.0).",
    )
    parser.add_argument(
        "--percentile",
        type=int,
        default=95,
        help="Percentile compared against the threshold (default: 95).",
    )
    parser.add_argument(
        "--include-cart",
        action="store_true",
        help=(
            "Also exercise the write path by adding a book to each "
            "user's cart. Mutates data: use a throwaway database."
        ),
    )
    parser.add_argument(
        "--book-id",
        type=int,
        default=1,
        help="Book used by --include-cart.",
    )
    parser.add_argument(
        "--json-out",
        default=None,
        help="Write the full report to this path as JSON.",
    )
    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)

    if args.users < 1:
        print("--users must be at least 1", file=sys.stderr)
        return 2

    report = run_load_test(
        base_url=args.base_url,
        users=args.users,
        requests_per_user=args.requests_per_user,
        timeout=args.timeout,
        threshold=args.threshold,
        percentile=args.percentile,
        include_cart=args.include_cart,
        book_id=args.book_id,
    )

    print(format_report(report))

    if args.json_out:
        with open(args.json_out, "w", encoding="utf-8") as handle:
            json.dump(asdict(report), handle, indent=2)
        print(f"\nJSON report written to {args.json_out}")

    return 0 if report.passed else 1


if __name__ == "__main__":
    sys.exit(main())
